// Typd's macOS injection helper. JXA: run by `osascript -l JavaScript`, never
// required by Node. The macOS twin of inject.ps1.
//
// Long-lived companion process. Reads one command per line on stdin and answers
// with exactly one line of JSON on stdout. Typd runs two copies of it (see
// inject-mac.js): "keys" presses keys and handles the clipboard, "ax" reads the
// screen through System Events. Either can do either; the split only keeps a
// slow screen read from ever queueing in front of a paste.
//
// The wire format is ASCII on purpose: `<id> <command> [base64]`. A pipe read
// can end in the middle of a multi-byte character; a line of ASCII cannot. Every
// answer carries its id, so an answer that arrives after Typd stopped waiting
// can never be taken for the answer to the next question.
//
// Everything here fails soft. A command that throws answers {ok:false, error}
// rather than killing the process, and every Objective-C call that might not be
// bridged on some macOS version sits behind a fallback.
//
// To try it by hand on a Mac, run the line below and type commands (they need
// the same permissions Typd does, granted to Terminal):
//   osascript -l JavaScript src/main/mac/inject-helper.js
//   1 focus
//   2 context
//   3 selection
//   4 copysel
//   5 field

ObjC.import('Foundation');
try { ObjC.import('AppKit'); } catch (e) { /* no NSPasteboard or NSWorkspace: the commands say so */ }
try { ObjC.import('CoreGraphics'); } catch (e) { /* key presses fall back to System Events */ }

// How much of the focused control to read. The same ceiling as inject.ps1, for
// the same reason: RESULTS.md measured the useful context at roughly 4K tokens,
// and relevance beats volume well before that.
const LIMIT = 8000;

const UTF8 = 4;                                  // NSUTF8StringEncoding
const STRING = 'public.utf8-plain-text';         // NSPasteboardTypeString
const COMMAND = 0x100000 | 0x8;                  // kCGEventFlagMaskCommand | left ⌘ (NX_DEVICELCMDKEYMASK)
const SESSION_TAP = 1;                           // kCGSessionEventTap
const KEY_V = 9;                                 // kVK_ANSI_V
const KEY_C = 8;                                 // kVK_ANSI_C

// nspasteboard.org's markers, which clipboard managers (Maccy, Paste, Raycast,
// Alfred) honour: a dictation is transient and machine-made, so it stays out of
// their history -- the macOS form of inject.ps1's Add-Private.
const TRANSIENT = 'org.nspasteboard.TransientType';
const AUTOGEN = 'org.nspasteboard.AutoGeneratedType';

// Saved: the formats people actually paste back. Every type would be more
// faithful, but asking an app for all of its lazily provided types (Office
// offers dozens) can take long enough to be felt on every paste. Legacy names
// (NSStringPboardType and friends) are derived by the system from these.
const KEEP = [
  STRING, 'public.utf16-external-plain-text', 'public.rtf', 'com.apple.flat-rtfd', 'public.html',
  'public.png', 'public.tiff', 'public.jpeg', 'com.adobe.pdf',
  'public.file-url', 'public.url', 'public.url-name'
];

const ENV = (function () {
  try { return ObjC.deepUnwrap($.NSProcessInfo.processInfo.environment) || {}; } catch (e) { return {}; }
})();

// TYPD_MAC_KEYS=system-events presses keys through System Events instead of
// CoreGraphics: slower, but the escape hatch if posted events go missing.
const FORCE_SYSTEM_EVENTS = ENV.TYPD_MAC_KEYS === 'system-events';

/* ---------------------------------------------------------------- bridge */

function isNil(o) {
  if (o === null || o === undefined) return true;
  try { return typeof o.isNil === 'function' && o.isNil(); } catch (e) { return false; }
}

/** NSString (or nil) to a JS string, '' for nil. */
function str(o) {
  if (isNil(o)) return '';
  try { const v = ObjC.unwrap(o); return typeof v === 'string' ? v : ''; } catch (e) { return ''; }
}

/** NSArray of NSString to a JS array. */
function list(o) {
  if (isNil(o)) return [];
  try { const v = ObjC.deepUnwrap(o); return Array.isArray(v) ? v : []; } catch (e) { return []; }
}

function message(e) {
  return String((e && e.message) || e || 'error');
}

function fromBase64(b64) {
  const data = $.NSData.alloc.initWithBase64EncodedStringOptions($(b64), 0);
  if (isNil(data)) throw new Error('bad base64');
  return str($.NSString.alloc.initWithDataEncoding(data, UTF8));
}

/**
 * A C function, whether or not this macOS's BridgeSupport describes it -- the
 * permission calls are newer than most of those files.
 */
function cfn(name, signature) {
  try { if (typeof $[name] !== 'undefined') return $[name]; } catch (e) { /* try binding it */ }
  try { ObjC.bindFunction(name, signature); if (typeof $[name] !== 'undefined') return $[name]; } catch (e) { /* not here */ }
  return null;
}

let stdout = null;

// Node reads line-delimited JSON, so every response must be one line. A file
// handle writes straight to the pipe -- nothing is buffered, nothing is held.
function emit(obj) {
  if (!stdout) stdout = $.NSFileHandle.fileHandleWithStandardOutput;
  stdout.writeData($(JSON.stringify(obj) + '\n').dataUsingEncoding(UTF8));
}

/**
 * Let notifications queued for this process land. Nothing here runs a run loop
 * -- it blocks reading stdin -- and NSWorkspace's idea of the frontmost app and
 * the keyboard layout are both kept current by notifications delivered on it.
 * Two milliseconds of run loop before each read keeps them honest.
 */
function pump() {
  try { $.NSRunLoop.currentRunLoop.runUntilDate($.NSDate.dateWithTimeIntervalSinceNow(0.002)); } catch (e) { /* stale at worst */ }
}

function sleep(seconds) {
  try { $.NSThread.sleepForTimeInterval(seconds); } catch (e) { delay(seconds); }
}

/** The frontmost app's name, without System Events: no permission, no Apple event. */
function frontName() {
  pump();
  try {
    const app = $.NSWorkspace.sharedWorkspace.frontmostApplication;
    return isNil(app) ? '' : str(app.localizedName);
  } catch (e) {
    return '';
  }
}

/* -------------------------------------------------------------- clipboard */

// The clipboard dance, done here rather than through Electron's clipboard
// because Electron writes one item of one kind at a time -- not several files
// copied in Finder, not the markers that keep a write private, and it cannot
// tell whether the user copied something since (the change count does).

function board() {
  return $.NSPasteboard.generalPasteboard;
}

function changeCount() {
  return Number(board().changeCount);
}

/** What the user had copied, item by item, in the formats worth keeping. */
function snapshot() {
  const items = [];
  const all = board().pasteboardItems;
  if (isNil(all)) return items;
  const n = Math.min(Number(all.count), 64);
  for (let i = 0; i < n; i++) {
    const item = all.objectAtIndex(i);
    const keep = [];
    for (const type of list(item.types)) {
      if (KEEP.indexOf(type) === -1) continue;
      try {
        const data = item.dataForType(type);
        if (!isNil(data)) keep.push([type, data]);
      } catch (e) { /* one format is not worth the rest */ }
    }
    if (keep.length) items.push(keep);
  }
  return items;
}

/**
 * Empty the clipboard for a write. Current-host-only keeps it off Universal
 * Clipboard -- your other devices -- the macOS form of CanUploadToCloudClipboard.
 */
function prepare(pb) {
  try { pb.prepareForNewContentsWithOptions(1); return; } catch (e) { /* before macOS 12 */ }
  pb.clearContents;
}

function writePrivate(text) {
  const pb = board();
  prepare(pb);
  const ok = pb.setStringForType($(text), STRING);
  try {
    pb.setStringForType($(''), TRANSIENT);
    pb.setStringForType($(''), AUTOGEN);
  } catch (e) { /* the text is what matters */ }
  return Boolean(ok);
}

function writeItems(items) {
  const objects = items.map(function (pairs, k) {
    const item = $.NSPasteboardItem.alloc.init;
    pairs.forEach(function (pair) { item.setDataForType(pair[1], pair[0]); });
    // Already in their clipboard history once; don't add it again.
    if (k === 0) item.setDataForType($.NSData.data, TRANSIENT);
    return item;
  });
  const pb = board();
  prepare(pb);
  return Boolean(pb.writeObjects($(objects)));
}

/* ------------------------------------------------------------------- keys */

function cgReady() {
  try {
    return typeof $.CGEventCreateKeyboardEvent !== 'undefined' &&
      typeof $.CGEventSetFlags !== 'undefined' && typeof $.CGEventPost !== 'undefined';
  } catch (e) {
    return false;
  }
}

function keyEvent(code, down) {
  const ev = $.CGEventCreateKeyboardEvent(null, code, down);
  if (isNil(ev)) throw new Error('no keyboard event');
  $.CGEventSetFlags(ev, COMMAND);
  return ev;
}

/**
 * The key that types `ch` with ⌘ held, on the keyboard layout in use now.
 *
 * Shortcuts follow the layout: on Turkish F the V key types C, so ⌘ on the V
 * key would copy where it should paste. The key is found by asking AppKit what
 * each key would type. The usual answer -- QWERTY, QWERTZ, AZERTY, Turkish Q --
 * is the first one tried; a layout with no Latin letters (Russian, Greek)
 * answers nothing useful, and there the ANSI key is right, because macOS falls
 * back to it for shortcuts.
 */
function keyFor(ch, fallback) {
  try {
    const probe = function (code) {
      const ns = $.NSEvent.eventWithCGEvent(keyEvent(code, true));
      return isNil(ns) ? '' : str(ns.characters).toLowerCase();
    };
    pump();   // let a layout switch since the last command reach this process
    const usual = probe(fallback);
    if (usual === ch || usual === '') return fallback;
    for (let code = 0; code <= 50; code++) {
      if (code !== fallback && probe(code) === ch) return code;
    }
  } catch (e) { /* the ANSI key, as everywhere else */ }
  return fallback;
}

let systemEventsApp = null;
function systemEvents() {
  if (!systemEventsApp) systemEventsApp = Application('System Events');
  return systemEventsApp;
}

/**
 * Press ⌘ plus a letter in the frontmost app. A CoreGraphics event is ~1 ms and
 * needs only Accessibility; System Events is the fallback, slower and needing
 * Automation as well, but layout-aware by construction.
 */
function press(ch, fallback) {
  if (!FORCE_SYSTEM_EVENTS && cgReady()) {
    try {
      const code = keyFor(ch, fallback);
      const down = keyEvent(code, true);
      const up = keyEvent(code, false);
      $.CGEventPost(SESSION_TAP, down);
      $.CGEventPost(SESSION_TAP, up);
      return 'cgevent:' + code;
    } catch (e) { /* fall through */ }
  }
  systemEvents().keystroke(ch, { using: 'command down' });
  return 'system-events';
}

/* ------------------------------------------------------------------ paste */

let saved = null;   // the user's clipboard while ours is on it
let ours = -1;      // the change count our write produced

// put <base64 text>: save the user's clipboard, write ours privately, ⌘V.
// If anything fails the text is left on the clipboard: a dictation is never lost.
function put(arg) {
  try {
    const text = fromBase64(arg);
    saved = snapshot();
    if (!writePrivate(text)) throw new Error('could not write the clipboard');
    ours = changeCount();
    return { ok: true, via: press('v', KEY_V) };
  } catch (e) {
    return { ok: false, error: message(e) };
  }
}

// copy <base64 text>: leave text on the clipboard for the user to paste themselves.
function copy(arg) {
  try {
    if (!writePrivate(fromBase64(arg))) throw new Error('could not write the clipboard');
    saved = null;
    return { ok: true };
  } catch (e) {
    return { ok: false, error: message(e) };
  }
}

// Put the user's clipboard back -- unless something has written to it since our
// paste (they copied something), which the change count tells us exactly.
function restore() {
  let done = false;
  try {
    if (saved !== null && changeCount() === ours) {
      if (saved.length) writeItems(saved);
      else board().clearContents;
      done = true;
    }
  } catch (e) { /* theirs stays ours; nothing is lost but the old clipboard */ }
  saved = null;
  return { ok: true, restored: done };
}

/* -------------------------------------------------------------- selection */

// The selection, taken the universal way: copy it and read the clipboard.
//
// Accessibility is the elegant path -- silent, and it disturbs nothing -- but
// web views and Electron apps often keep their text out of the accessibility
// tree until a screen reader asks for it, and some controls have no notion of a
// selection at all. ⌘C has no such gaps. It works wherever copying works,
// which is everywhere, because it asks the application to do the one thing it
// already knows how to do.
//
// The hazard is that ⌘C with nothing selected leaves the clipboard alone, so a
// naive read returns whatever the user copied an hour ago and calls it a
// selection. A sentinel closes that: write a marker, copy, and if the marker
// survived then nothing was highlighted.
//
// The user's clipboard is put back either way. paste already does this dance,
// so the cost is understood -- what is new here is that we are reading rather
// than writing, and the receiving application needs a moment to answer.
function copiedSelection() {
  const out = { ok: true, process: '', title: '', method: 'none', text: '', length: 0, ms: 0 };
  const started = Date.now();
  let theirs = null;
  let wrote = false;

  try {
    out.process = frontName();

    // Text, with whatever rich formats and files came with it, is put back
    // whole. A clipboard holding no text at all -- an image on its own, or some
    // app's private format -- is declined rather than risked: the clipboard is
    // the user's, and losing its contents to a probe would be a real cost.
    const types = list(board().types);
    if (types.indexOf(STRING) !== -1) {
      theirs = snapshot();
    } else if (types.length) {
      out.method = 'clipboard-not-text';
      out.ms = Date.now() - started;
      return out;
    }

    let marker = 'typd-probe-';
    try { marker += str($.NSUUID.UUID.UUIDString); } catch (e) { marker += String(Math.random()).slice(2); }
    writePrivate(marker);
    wrote = true;
    const before = changeCount();

    press('c', KEY_C);

    // The copy is asynchronous: the keystroke returns long before the target
    // application has serviced it and written to the clipboard. Poll the change
    // count -- cheap, and it reads nothing -- so a fast app costs 15 ms instead
    // of a flat 300.
    let copied = marker;
    for (let i = 0; i < 20; i++) {
      sleep(0.015);
      if (changeCount() === before) continue;
      const s = board().stringForType(STRING);
      if (isNil(s)) continue;   // cleared, not yet written
      copied = str(s);
      if (copied !== marker) break;
    }

    if (copied === marker) {
      out.method = 'no-selection';
    } else {
      out.text = copied;
      out.length = copied.length;
      out.method = 'clipboard';
    }
  } catch (e) {
    out.ok = false;
    out.method = 'error: ' + message(e);
  } finally {
    if (wrote) {
      try {
        if (theirs && theirs.length) writeItems(theirs);
        else board().clearContents;
      } catch (e) { /* nothing more to try */ }
    }
  }

  out.ms = Date.now() - started;
  return out;
}

/* ----------------------------------------------------- accessibility (ax) */

/**
 * Errors that are about permission rather than about this control: Automation
 * for System Events refused (-1743), or Typd not trusted for Accessibility.
 * Those stop the whole read and are reported, so Typd can say which switch.
 */
function fatal(e) {
  const n = Number(e && e.errorNumber);
  const m = message(e);
  if (n === -1743 || /not (authori[sz]ed|allowed) to send apple ?events/i.test(m)) return 'automation';
  if (n === -25211 || /assistive access/i.test(m)) return 'assistive';
  return null;
}

/** One accessibility attribute, or undefined when this element has no such thing. */
function attr(el, name) {
  try {
    return el.attributes.byName(name).value();
  } catch (e) {
    if (fatal(e)) throw e;
    return undefined;
  }
}

function frontProcess() {
  const found = systemEvents().applicationProcesses.whose({ frontmost: true })();
  return found && found.length ? found[0] : null;
}

function processName(p) {
  try {
    return String(p.name() || '');
  } catch (e) {
    if (fatal(e)) throw e;
    return frontName();
  }
}

function windowTitle(p) {
  const win = attr(p, 'AXFocusedWindow');
  if (!win) return '';
  const title = attr(win, 'AXTitle');
  return typeof title === 'string' ? title : '';
}

function blocked(out, e) {
  const kind = fatal(e);
  if (kind) out.denied = kind;
  else out.error = message(e);
  if (!out.process) out.process = frontName();
}

/**
 * Where the caret is, from AXSelectedTextRange. System Events does not document
 * the shape it hands a range back in -- {location, length} or a 1-based
 * {start, end} -- but for a collapsed caret, which is when this is read, the
 * larger of the two numbers is the caret under either reading, to within one
 * character.
 */
function caretAt(range, length) {
  let a, b;
  if (Array.isArray(range) && range.length >= 2) {
    a = Number(range[0]); b = Number(range[1]);
  } else if (range && typeof range === 'object' && 'location' in range) {
    a = Number(range.location); b = a + Number(range.length || 0);
  } else {
    return null;
  }
  if (!isFinite(a) || !isFinite(b)) return null;
  return Math.max(0, Math.min(length, Math.max(a, b)));
}

function focus() {
  const out = { ok: true, process: '', title: '' };
  try {
    const p = frontProcess();
    if (!p) { out.process = frontName(); return out; }
    out.process = processName(p);
    out.title = windowTitle(p);
  } catch (e) {
    blocked(out, e);
  }
  return out;
}

// The front app's bundle id, and whether it is built on a web engine (Chromium, Electron, CEF):
// read from the app's own Frameworks folder, no Apple event. Cached per bundle path.
const webCache = {};
function frontBundle() {
  const out = { bundle: '', web: false };
  try {
    const app = $.NSWorkspace.sharedWorkspace.frontmostApplication;
    if (isNil(app)) return out;
    out.bundle = str(app.bundleIdentifier);
    const url = app.bundleURL;
    const root = isNil(url) ? '' : str(url.path);
    if (!root) return out;
    if (!(root in webCache)) {
      let web = false;
      try {
        const list = ObjC.deepUnwrap($.NSFileManager.defaultManager.contentsOfDirectoryAtPathError($(root + '/Contents/Frameworks'), null)) || [];
        web = list.some(function (n) { return /^(Electron Framework|Chromium Embedded Framework|.*(Chrome|Chromium|Edge|Brave|Opera|Vivaldi|Arc).* Framework)\.framework$/i.test(String(n)); });
      } catch (e) { /* no Frameworks folder: not a web-engine app */ }
      webCache[root] = web;
    }
    out.web = webCache[root];
  } catch (e) { /* unknown: the classifier treats missing facts as "paste" */ }
  return out;
}

// Can the focused element take a paste? Facts only (src/main/pasteTarget.js decides, tested in
// bench/copy-popup.js): its role and subrole, whether its AXValue is settable, the front app's
// bundle id and web engine. Never its text. `el` is the AXFocusedUIElement already read, or null.
function fieldFacts(el) {
  const f = frontBundle();
  f.focused = Boolean(el);
  f.role = ''; f.subrole = ''; f.settable = null;
  if (!el) return f;
  const role = attr(el, 'AXRole');
  f.role = typeof role === 'string' ? role : '';
  const sub = attr(el, 'AXSubrole');
  f.subrole = typeof sub === 'string' ? sub : '';
  if (!/^AX(TextField|TextArea|ComboBox|SearchField)$/.test(f.role)) {
    try { f.settable = Boolean(el.attributes.byName('AXValue').settable()); } catch (e) { if (fatal(e)) throw e; f.settable = null; }
  }
  return f;
}

// field: the facts alone, for the second look just before a dictation would be offered instead
// of pasted (the focus may have moved into a text field while the user talked).
function field() {
  const out = { ok: true, field: null };
  try {
    const p = frontProcess();
    const el = p ? attr(p, 'AXFocusedUIElement') : null;
    out.field = fieldFacts(el || null);
  } catch (e) {
    blocked(out, e);
    out.field = { error: out.denied || 'error' };
  }
  return out;
}

// The focused control's text, the way inject.ps1's Get-FocusText and
// Get-Context take it: the top of the document, or -- when there is a caret --
// the window immediately before it, which is what the speaker is actually
// looking at and dictating into. Then the last LIMIT characters of that.
function context() {
  const out = { ok: true, process: '', title: '', text: '', field: null };
  try {
    const p = frontProcess();
    if (!p) { out.process = frontName(); out.field = fieldFacts(null); return out; }
    out.process = processName(p);
    out.title = windowTitle(p);

    const el = attr(p, 'AXFocusedUIElement');
    // Whether a paste can land there (pasteTarget.js), from the same element: a few Apple events more.
    try { out.field = fieldFacts(el || null); } catch (e) { if (fatal(e)) throw e; out.field = { error: 'error' }; }
    const value = el ? attr(el, 'AXValue') : undefined;
    if (typeof value === 'string' && value) {
      let text = value.slice(0, LIMIT);
      const caret = caretAt(attr(el, 'AXSelectedTextRange'), value.length);
      if (caret !== null) {
        const near = value.slice(Math.max(0, caret - LIMIT), caret);
        if (near.length > 40) text = near;
      }
      if (text.length > LIMIT) text = text.slice(text.length - LIMIT);
      out.text = text;
    }
  } catch (e) {
    blocked(out, e);
  }
  return out;
}

// What the user has actually highlighted, as opposed to the whole control.
//
// AXSelectedText is the only attribute that models a selection. A control
// without it is reported as unsupported rather than guessed at, and so is one
// with a selection but no string value to check it against -- see below.
function selection() {
  const out = { ok: true, process: '', title: '', method: 'none', text: '', length: 0, docLength: 0 };
  try {
    const p = frontProcess();
    if (!p) { out.process = frontName(); out.method = 'no-process'; return out; }
    out.process = processName(p);

    const el = attr(p, 'AXFocusedUIElement');
    if (!el) { out.method = 'no-focused-element'; return out; }

    const sel = attr(el, 'AXSelectedText');
    if (typeof sel !== 'string') { out.method = 'no-selected-text'; return out; }

    // Chromium -- every browser and every Electron app -- has been seen on
    // Windows to hand back the WHOLE DOCUMENT as the selection when the real
    // selection does not map onto its range model, and trusting that rewrote an
    // entire page over one sentence. The same guard applies here: a selection
    // identical to the document is genuine select-all or a control telling us
    // nothing, the two are indistinguishable from here, and ⌘C is right either
    // way. Without the document there is nothing to guard with, so that is
    // deferred to ⌘C too.
    const doc = attr(el, 'AXValue');
    if (typeof doc !== 'string') { out.method = 'no-value'; return out; }
    out.docLength = doc.length;

    if (sel.length > 0 && sel === doc) {
      out.method = 'selection-is-whole-document';
    } else if (sel.length > 0) {
      out.text = sel;
      out.length = sel.length;
      out.method = 'ax';
    } else {
      // A caret with nothing highlighted, in a control that does model
      // selections: there is simply nothing selected.
      out.method = 'caret-only';
    }
  } catch (e) {
    blocked(out, e);
    out.method = out.denied ? 'denied-' + out.denied : 'error';
  }
  return out;
}

/* ------------------------------------------------------------ permissions */

/** Input Monitoring for Typd (this process answers for the app that started it). */
function listenAccess() {
  const check = cfn('IOHIDCheckAccess', ['int', ['int']]);
  if (check) {
    try {
      const r = Number(check(1));   // kIOHIDRequestTypeListenEvent
      return r === 0 ? 'granted' : r === 1 ? 'denied' : 'unknown';
    } catch (e) { /* try the CoreGraphics form */ }
  }
  const preflight = cfn('CGPreflightListenEventAccess', ['bool', []]);
  if (preflight) {
    try { return preflight() ? 'granted' : 'missing'; } catch (e) { /* cannot tell */ }
  }
  return null;
}

/** Ask for Input Monitoring: puts Typd in the list, with macOS's own prompt the first time. */
function requestListen() {
  const request = cfn('IOHIDRequestAccess', ['bool', ['int']]);
  if (request) {
    try { return { ok: true, granted: Boolean(request(1)) }; } catch (e) { /* try the CoreGraphics form */ }
  }
  const cg = cfn('CGRequestListenEventAccess', ['bool', []]);
  if (cg) {
    try { return { ok: true, granted: Boolean(cg()) }; } catch (e) { /* nothing left */ }
  }
  return { ok: false, error: 'unavailable' };
}

/**
 * The first Apple event to System Events, sent when Typd chooses rather than
 * in the middle of a dictation: macOS asks the user about Automation on the
 * first one, and this waits for their answer.
 */
function prime() {
  try {
    const p = frontProcess();
    return { ok: true, process: p ? processName(p) : '' };
  } catch (e) {
    return { ok: false, error: fatal(e) || message(e) };
  }
}

/** macOS 26's pasteboard privacy setting for this app, logged so a prompt per paste can be explained. */
function pasteboardAccess() {
  try {
    const b = board().accessBehavior;
    return b === undefined ? null : Number(b);
  } catch (e) {
    return null;
  }
}

/* ------------------------------------------------------------------- loop */

const COMMANDS = {
  put: put,
  copy: copy,
  restore: restore,
  copysel: copiedSelection,
  front: function () { return { ok: true, process: frontName() }; },
  access: function () { return { ok: true, listen: listenAccess() }; },
  focus: focus,
  context: context,
  field: field,
  selection: selection,
  prime: prime,
  'request-listen': requestListen
};

function handle(line) {
  const parts = line.split(' ');
  const id = Number(parts[0]);
  const name = parts[1] || '';
  let res;
  try {
    res = Object.prototype.hasOwnProperty.call(COMMANDS, name)
      ? COMMANDS[name](parts[2] || '')
      : { ok: false, error: 'unknown command' };
  } catch (e) {
    res = { ok: false, error: message(e) };
  }
  if (!res) return;
  res.id = id;
  emit(res);
}

// Touch the bridges once here, so their setup is paid during launch rather than
// on the first real command. Nothing here reads the clipboard's contents or
// sends an Apple event: either could put a macOS prompt on screen before Typd
// has explained why.
function warm() {
  frontName();
  try { changeCount(); } catch (e) { /* reported by the first real command */ }
  if (cgReady()) keyFor('v', KEY_V);
}

function run(argv) {
  warm();
  emit({
    ready: true,
    lane: (argv && argv[0]) || '',
    keys: FORCE_SYSTEM_EVENTS ? 'system-events' : cgReady() ? 'cgevent' : 'system-events (no CoreGraphics bridge)',
    pasteboardAccess: pasteboardAccess()
  });

  const input = $.NSFileHandle.fileHandleWithStandardInput;
  let pending = '';
  for (;;) {
    let data;
    try { data = input.availableData; } catch (e) { break; }
    if (isNil(data) || Number(data.length) === 0) break;   // stdin closed: Typd is going away
    pending += str($.NSString.alloc.initWithDataEncoding(data, UTF8));
    let i;
    while ((i = pending.indexOf('\n')) !== -1) {
      const line = pending.slice(0, i).trim();
      pending = pending.slice(i + 1);
      if (line) handle(line);
    }
  }
}
